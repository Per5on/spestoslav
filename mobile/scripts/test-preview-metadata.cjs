const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const source = require("../preview.json");
const config = require("../app.config.js");
const base = require("../app.json").expo;
const registry = require("../../docs/references/preview-sequence.json");
assert.match(source.sequence, /^[0-9]{3}$/);
assert.equal(config.name, `Спестовник ${source.label ?? String(Number(source.sequence)).padStart(2,"0")}`);
assert.equal(config.android.versionCode, Number(source.sequence));
const hybrid = source.label?.endsWith("-hybrid") ?? false;
assert.equal(config.android.package, base.android.package + (hybrid ? ".hybrid" : ""));
assert.equal(config.version, source.version);
assert.equal(require("../package.json").version, source.version);
assert.equal(base.name, undefined);
assert.equal(base.version, undefined);
assert.equal(base.android.versionCode, undefined);
const next = Math.max(Number(source.sequence), ...registry.versions.map(v => Number(v.version) + 1));
assert.equal(registry.next_version, String(next).padStart(3,"0"));
assert.equal(config.android.permissions.includes("android.permission.CAMERA"), true);
assert.equal(config.android.blockedPermissions.includes("android.permission.CAMERA"), false);
assert.equal(config.android.blockedPermissions.includes("android.permission.RECORD_AUDIO"), true);
const [, splash] = config.plugins.find(plugin => Array.isArray(plugin) && plugin[0] === "expo-splash-screen");
assert(fs.existsSync(path.resolve(__dirname, "..", splash.image)));
console.log("Preview metadata checks passed: one source for app label/versionCode/workflow, generated next-number registry and camera-only permission.");
